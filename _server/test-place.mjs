import koffi from 'koffi';
import { findWindowByPid, focusWindow, makeBorderless } from './src/win32.js';
const user32 = koffi.load('user32.dll');
const GetWindowRect = user32.func('bool GetWindowRect(void *h, _Out_ int32 *r)');
const GetClientRect = user32.func('bool GetClientRect(void *h, _Out_ int32 *r)');
const ClientToScreen = user32.func('bool ClientToScreen(void *h, _Out_ int32 *p)');
const SetWindowPos = user32.func('bool SetWindowPos(void *h, void *a, int x, int y, int cx, int cy, uint f)');
const SetWindowLongW = user32.func('int SetWindowLongW(void *h, int i, int v)');
const pid = Number(process.argv[2]);
const h = findWindowByPid(pid);
console.log('hwnd', h);
const rect = [0,0,0,0], cr = [0,0,0,0], pt = [0,0];
GetWindowRect(h, rect); GetClientRect(h, cr); ClientToScreen(h, pt);
console.log('outer', rect, 'client', cr, 'clientOrigin', pt);
SetWindowPos(h, -1, 0, 0, 640, 480, 0x0040);
focusWindow(h);
await new Promise(r => setTimeout(r, 4000));
GetWindowRect(h, rect); GetClientRect(h, cr); ClientToScreen(h, pt);
console.log('after pos outer', rect, 'client', cr, 'origin', pt);
console.log('alive', !process.kill(pid, 0) ? 'yes' : 'no');
